// Bundle static text files (skill, install script) into TS modules so the
// Worker can serve them at runtime. Run before build/deploy via npm scripts.
//
// Inputs:  ../skill/SKILL.md, ./scripts/install.sh.tmpl
// Outputs: src/static.generated.ts (gitignored)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const workerRoot = resolve(here, "..");
const repoRoot = resolve(workerRoot, "..");

const skill = readFileSync(resolve(repoRoot, "skill", "SKILL.md"), "utf8");
const installScript = readFileSync(resolve(here, "install.sh.tmpl"), "utf8");

const out = `// AUTO-GENERATED by scripts/bundle-static.mjs — do not edit.
export const SKILL_MD = ${JSON.stringify(skill)};
export const INSTALL_SH = ${JSON.stringify(installScript)};
`;

writeFileSync(resolve(workerRoot, "src", "static.generated.ts"), out);
process.stdout.write(`bundled: SKILL.md (${skill.length} chars), install.sh (${installScript.length} chars)\n`);
